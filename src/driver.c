#include "suru/driver.h"
#include "suru/arena.h"
#include "suru/parser.h"
#include "suru/sema.h"
#include "suru/bcc.h"
#include "suru/verify.h"
#include "suru/vm.h"

#include <string.h>

/* Deterministic execution heap-mode selection (Stage 11D T1).
 * Only the legacy heap is implemented; the "new" objmodel mode arrives with the
 * atomic cutover. Default is legacy. An explicit, unsupported value fails
 * clearly rather than silently selecting a mode. */
int s_driver_heap_mode(void) {
    const char *e = getenv("SURU_HEAP");
    if (!e || !*e) return S_DRIVER_HEAP_LEGACY;
    if (strcmp(e, "legacy") == 0) return S_DRIVER_HEAP_LEGACY;
    fprintf(stderr, "suru: unsupported SURU_HEAP=\"%s\" (only \"legacy\" is implemented)\n", e);
    return -1;
}

int s_driver_compile(const char *file, const char *src, s_size len,
                     s_bc_module *out) {
    s_arena arena;
    s_arena_init(&arena);
    s_diag_ctx diag;
    s_diag_init(&diag);
    s_diag_set_source(&diag, src, len);

    s_parser p;
    if (!s_parse(&p, file, src, len, &arena, &diag)) {
        s_diag_print(&diag);
        s_diag_dispose(&diag);
        s_arena_dispose(&arena);
        return -1;
    }
    if (s_diag_has_errors(&diag)) {
        s_diag_print(&diag);
        s_diag_dispose(&diag);
        s_arena_dispose(&arena);
        return -1;
    }
    if (!s_sema_run(&p.mod, &arena, &diag)) {
        s_diag_print(&diag);
        s_diag_dispose(&diag);
        s_arena_dispose(&arena);
        return -1;
    }
    if (!s_bcc_run(&p.mod, &arena, &diag, out)) {
        s_diag_print(&diag);
        s_diag_dispose(&diag);
        s_arena_dispose(&arena);
        return -1;
    }
    if (s_verify_module(out) != 0) {
        fprintf(stderr, "suru: internal error: generated bytecode failed verification\n");
        s_bc_module_dispose(out);
        s_diag_dispose(&diag);
        s_arena_dispose(&arena);
        return -1;
    }

    s_diag_dispose(&diag);
    s_arena_dispose(&arena);
    return 0;
}

int s_driver_run_module_args(s_bc_module *m, int argc, char **argv) {
    if (s_driver_heap_mode() < 0) return 2;
    s_vm *vm = s_vm_create(m);
    if (!vm) {
        return 1;
    }
    s_vm_set_args(vm, argc, argv);
    int rc = s_vm_run(vm);
    s_vm_destroy(vm);
    return rc;
}

int s_driver_run_module(s_bc_module *m) {
    return s_driver_run_module_args(m, 0, NULL);
}
